"""
Makes web-sized copies of every image the site uses, and records each image's
size so the grid can lay itself out before the images arrive.

Run from the repo root after adding images:   python3 tools/optimize_images.py

For each image (e.g. foo.jpg) it writes, next to it:
  foo.w800.webp   small copy (grid tiles, about photos)
  foo.w1200.webp  medium copy (grid tiles on Retina screens)
  foo.w1600.webp  large copy (project pages on big screens)
and rewrites js/image-sizes.js. Originals are kept as-is.
"""
import json, os, re
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
src = open("js/projects.js").read()
paths = sorted(set(re.findall(r'"(assets/[^"]+\.(?:jpe?g|png))"', src, re.I)))
WIDTHS = [800, 1200, 1600]
sizes = {}
for p in paths:
    if not os.path.exists(p):
        print("missing:", p); continue
    im = Image.open(p)
    im = im.convert("RGBA" if im.mode in ("RGBA", "LA", "P") else "RGB")
    sizes[p] = [im.width, im.height]
    base = os.path.splitext(p)[0]
    for w in WIDTHS:
        out = f"{base}.w{w}.webp"
        if os.path.exists(out) and os.path.getmtime(out) >= os.path.getmtime(p):
            continue
        c = im.copy()
        if c.width > w:
            c = c.resize((w, round(c.height * w / c.width)), Image.LANCZOS)
        c.save(out, "WEBP", quality=80, method=6)
with open("js/image-sizes.js", "w") as f:
    f.write("/* Generated by tools/optimize_images.py, do not edit by hand. [width, height] of each image. */\n")
    f.write("const IMAGE_SIZES = " + json.dumps(sizes, indent=0) + ";\n")
print(len(sizes), "images processed")
